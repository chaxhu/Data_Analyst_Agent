from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add

class AgenticSchema(BaseModel):
    messages : Annotated[list,add] = Field(..., description="A list of messages to be processed by the agent.")
    curated_ques : str = Field(..., description="A curated question that the agent will use to generate a response.")
    prompt_query_context : str = Field(..., description="A detailed prompt with SQL DB context that will help agent to generate more accurate SQL queries.")
    is_safe : Literal["Yes", "No"] = Field(..., description="Indicates whether the generated SQL query is safe to execute or not.")
    generated_sql_query : str = Field(..., description="The SQL query generated by the agent based on the provided messages and curated question.")
    sql_query_execution_result : str = Field(..., description="The result of executing the generated SQL query against the database.")
    final_answer : str = Field(..., description="The final answer generated by the agent after processing the messages, curated question, and SQL query execution result.")